/** Regenerate src/icon-data.ts from public/icons/128/*.webp. */
const fs = require('fs');
const slugs = ['aries','taurus','gemini','cancer','leo','virgo','libra','scorpio','sagittarius','capricorn','aquarius','pisces'];
let out = '/**\n * Generated by tools/gen-icon-data.cjs — the site zodiac disc icons\n * (public/assets/zodiac-icons/128, SDK icon set) inlined as data URIs so\n * SVG <image> nodes never race the renderer.\n */\nexport const ICON_URI: Record<string, string> = {\n';
for (const s of slugs) {
  const b64 = fs.readFileSync('public/icons/128/' + s + '.webp').toString('base64');
  out += '  ' + s + ": 'data:image/webp;base64," + b64 + "',\n";
}
out += '};\n';
fs.writeFileSync('src/icon-data.ts', out);
console.log('wrote src/icon-data.ts');
