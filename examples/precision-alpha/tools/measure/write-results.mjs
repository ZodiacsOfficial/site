/**
 * Writes the four-configuration write-up FROM the measurement's own JSON.
 *
 * Every figure in the prose below is read out of report.json rather than
 * typed. An earlier write-up in this project published 1.834" where the
 * comparator had said 1.8636"; generating the document removes that class
 * of error rather than promising to be careful.
 *
 *   node tools/measure/write-results.mjs [--in <dir>] [--out <file>]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i].replace(/^--/, ''), process.argv[i + 1]);
const IN = args.get('in') ?? new URL('../../../../docs/platform/evidence/precision-2026-09-20/raw/four-configurations', import.meta.url).pathname;
const OUT = args.get('out') ?? new URL('../../../../docs/platform/evidence/precision-2026-09-20/FOUR-CONFIGURATIONS.md', import.meta.url).pathname;

const r = JSON.parse(readFileSync(join(IN, 'report.json'), 'utf8'));
const a = (x, d = 6) => (x === null || x === undefined ? '—' : Number(x).toFixed(d));
const e = (x) => (x === null || x === undefined ? '—' : Number(x).toExponential(3));
const iso = (s) => s.replace('T', ' ').replace(/\.\d+Z$/, ' UTC');

const L = [];
const w = (...lines) => L.push(...lines);

w('# The four-configuration measurement', '',
  'Generated by `examples/precision-alpha/tools/measure/write-results.mjs` from',
  '`raw/four-configurations/report.json`. Every number below is read out of that',
  'file, not transcribed.', '',
  `Run: ${iso(r.when)}, Node ${r.node}.`, '');

w('## What was varied', '',
  'Two things, independently, and nothing else:', '',
  '| | backend | reduction |', '| --- | --- | --- |');
for (const k of ['A', 'B', 'C', 'D']) w(`| **${k}** | ${r.labels[k].backend} | ${r.labels[k].reduction} |`);
w('',
  'One reduction module runs over both backends, so a difference between two',
  'cells is the thing being varied and not a second implementation of the',
  'physics.', '',
  `> These are this mandate's labels. The earlier numerics track used "cell`,
  `> A..D" for a different 2×2 — prototype versus core engine, own clock versus`,
  `> pinned clock — and those figures are not these.`, '');

w('## Conditions', '',
  `- **Clock.** ${r.clock}`,
  `- **Conventions.** ${r.conventions}`,
  `- **Pack.** \`${r.inputs.pack.candidate ?? 'unnamed'}\`, SHA-256 \`${r.inputs.pack.digest}\`, self-consistent: ${r.inputs.pack.selfConsistent}. Authenticity: ${r.inputs.pack.authenticity}.`,
  `- **Kernel.** the pack's header names its input as \`${r.inputs.kernel.declaredInput?.file ?? 'unknown'}\`, SHA-256 \`${r.inputs.kernel.declaredInput?.sha256 ?? 'unknown'}\`, ${r.inputs.kernel.declaredInput?.bytes ?? '?'} bytes.`,
  `- **Instrument.** Swiss Ephemeris ${r.sets.corpus.swiss.binding}, backends actually used: ${r.sets.corpus.swiss.backends.join(', ')} — checked per call, because Swiss falls back to its Moshier series without complaint when the data files are missing and a run that fell back is not this configuration.`,
  '',
  `> ${r.caveat}`, '');

w('## Effective coverage, exactly', '',
  '| | start | stop |', '| --- | --- | --- |',
  `| pack, declared | ${r.coverage.pack.startEtSecTdb} s TDB | ${r.coverage.pack.stopEtSecTdb} s TDB |`,
  `| kernel segments | ${r.coverage.kernel.startEtSecTdb} s TDB | ${r.coverage.kernel.stopEtSecTdb} s TDB |`,
  `| **used here** | **${r.coverage.effective.startEtSecTdb} s TDB** (${iso(r.coverage.effective.startApproxUtc)}) | **${r.coverage.effective.stopEtSecTdb} s TDB** (${iso(r.coverage.effective.stopApproxUtc)}) |`,
  '',
  `The window is inset by ${r.coverage.effective.insetSec} s at each end: ${r.coverage.effective.insetWhy}.`, '');

for (const [name, s] of Object.entries(r.sets)) {
  w(`## Set: ${name}`, '', s.what, '');
  if (s.source) w(`Source: \`${s.source}\`.`, '');
  if (s.stepDays) w(`Step: ${s.stepDays} days — ${s.stepWhy}.`, '');
  w(`Instants offered: ${s.instantsOffered}. Body-epochs measured: ${s.allBodies.n} across all ten bodies, ${s.bodyCentresOnly.n} on the ${s.bodyCentresOnly.bodies.length}-body subset the earlier record reported.`, '');
  if (s.skipped.length) {
    const why = [...new Set(s.skipped.map((x) => x.why))];
    w(`Skipped: ${s.skipped.length} — ${why.join('; ')}. (${s.skipped.map((x) => x.id).join(', ')})`, '');
  }

  w('### Against Swiss, arcseconds', '',
    `**${s.bodyCentresOnly.bodies.join(', ')} only.** ${s.bodyCentresOnly.why}`, '',
    '| configuration | max | p50 | p95 | n |', '| --- | --- | --- | --- | --- |');
  for (const k of ['A', 'B', 'C', 'D']) {
    const v = s.bodyCentresOnly.vsSwissArcsec[k];
    w(`| ${k} — ${r.labels[k].backend}, ${r.labels[k].reduction} | ${a(v.max)} | ${a(v.p50)} | ${a(v.p95)} | ${v.n} |`);
  }
  w('', 'All ten bodies, for completeness:', '',
    '| configuration | max | p50 | p95 | n |', '| --- | --- | --- | --- | --- |');
  for (const k of ['A', 'B', 'C', 'D']) {
    const v = s.allBodies.vsSwissArcsec[k];
    w(`| ${k} | ${a(v.max)} | ${a(v.p50)} | ${a(v.p95)} | ${v.n} |`);
  }
  w('', `The six system barycentres alone reach ${a(s.systemBarycentresOnly.vsSwissArcsec.D.max)}″ on configuration D. ${s.systemBarycentresOnly.why}`, '');

  w('### Between configurations, arcseconds, all ten bodies', '',
    '| comparison | max | p50 | p95 |', '| --- | --- | --- | --- |');
  for (const [k, v] of Object.entries(s.allBodies.betweenConfigurationsArcsec)) {
    w(`| ${k} | ${a(v.max)} | ${a(v.p50)} | ${a(v.p95)} |`);
  }
  const c = s.allBodies.compositionResidualArcsec;
  w('', '### Do the two changes compose?', '',
    'The question is whether the separate headlines may be added, and it is',
    'answered by measurement rather than assumed. Signed differences, so two',
    'effects that cancelled could not pass as agreement:', '',
    '```',
    '| (D − A) − ((C − A) + (B − A)) |',
    '```', '',
    `| | max | p50 | p95 | n |`, '| --- | --- | --- | --- | --- |',
    `| residual, arcsec | ${e(c.max)} | ${e(c.p50)} | ${e(c.p95)} | ${c.n} |`, '');
}

const corpus = r.sets.corpus.allBodies.vsSwissArcsec;
const grid = r.sets.grid;
w('## What this settles', '', '### The two changes do compose',
  '',
  `On the pinned corpus the residual is at most ${e(r.sets.corpus.allBodies.compositionResidualArcsec.max)}″ and on the full`,
  `sweep at most ${e(grid.allBodies.compositionResidualArcsec.max)}″, against effects of ${a(r.sets.corpus.allBodies.betweenConfigurationsArcsec['reduction alone, kernel backend (A vs B)'].max, 4)}″ and`,
  `${a(r.sets.corpus.allBodies.betweenConfigurationsArcsec['compression alone, prototype reduction (A vs C)'].max, 6)}″. Compression and the corrected reduction act on this`,
  'reduction independently, so their separate sizes may be added — which is now',
  'a measurement rather than the assumption the mandate warned against making.',
  '',
  '### The pinned corpus reproduces the recorded figures exactly',
  '',
  '| | this run, all ten bodies | recorded |', '| --- | --- | --- |',
  `| prototype reduction, matched clock (A) | ${a(corpus.A.max)}″ max | 0.134444″ max |`,
  `| corrected reduction (B) | ${a(corpus.B.max)}″ max | 0.010730″ max |`,
  '',
  'The maxima agree to every digit. Percentiles differ in the last places',
  'because nearest-rank and interpolated conventions disagree on small samples;',
  'the maxima have no convention, which is why they are the check to read.',
  '',
  '### The 0.05″ incremental-compression target: met, separately',
  '',
  `Compression alone costs at most ${a(r.sets.corpus.allBodies.betweenConfigurationsArcsec['compression alone, prototype reduction (A vs C)'].max)}″ on the corpus and`,
  `${a(grid.allBodies.betweenConfigurationsArcsec['compression alone, prototype reduction (A vs C)'].max)}″ over the whole sweep, against a declared 0.05″. It is`,
  'reported against the uncompressed prototype, on the same reduction, so',
  'nothing else is folded into it.',
  '',
  '### The 0.5″ matched-convention target: met by the integrated build',
  '',
  `Configuration D, the pack and the corrected reduction together, reaches`,
  `${a(r.sets.corpus.bodyCentresOnly.vsSwissArcsec.D.max)}″ on the corpus and ${a(grid.bodyCentresOnly.vsSwissArcsec.D.max)}″ over the whole sweep, on the`,
  `${r.sets.corpus.bodyCentresOnly.bodies.length}-body subset the earlier record reported. Swiss and this kernel mean the same point for all ten.`,
  '',
  '### The 0.0107″ figure does NOT survive the broader test',
  '',
  `It is a property of sixteen epochs, not of the model. On the same bodies`,
  `over the full effective coverage — ${grid.bodyCentresOnly.n} body-epochs at`,
  `${r.sets.grid.stepDays}-day steps — configuration D reaches **${a(grid.bodyCentresOnly.vsSwissArcsec.D.max)}″**,`,
  `about ${(grid.bodyCentresOnly.vsSwissArcsec.D.max / r.sets.corpus.bodyCentresOnly.vsSwissArcsec.D.max).toFixed(1)}× the corpus figure, with a median of ${a(grid.bodyCentresOnly.vsSwissArcsec.D.p50)}″ and`,
  `a 95th percentile of ${a(grid.bodyCentresOnly.vsSwissArcsec.D.p95)}″. The corpus understates the ceiling, which`,
  'is what the nutation analysis already said about it, and the broader figure',
  'is the one to quote for the domain it covers.',
  '',
  '### Position and derivative, separately',
  '',
  'The backend states, pack against the uncompressed kernel, sampled on the',
  'sweep. Position and derivative are different quantities with different',
  'budgets and are not combined:',
  '',
  '| body | position max, km | position p50, km | derivative max, km/s | derivative p50, km/s |',
  '| --- | --- | --- | --- | --- |');
for (const [b, v] of Object.entries(r.derivative.perBody)) {
  w(`| ${b} | ${e(v.positionKm.max)} | ${e(v.positionKm.p50)} | ${e(v.velocityKmPerSec.max)} | ${e(v.velocityKmPerSec.p50)} |`);
}
const bm = r.barycentricMoon;
w('',
  '### The barycentric Moon: the target is still missed',
  '',
  `Target: ${bm.target}.`,
  '',
  `| | value |`, '| --- | --- |',
  `| recorded sampled | ${bm.recorded.sampledKm} km |`,
  `| **recorded proven bound** | **${bm.recorded.provenKm} km** |`,
  `| re-measured here, sampled, ${bm.remeasuredSampledBarycentricMoonKm.n} instants | ${a(bm.remeasuredSampledBarycentricMoonKm.max, 5)} km |`,
  '',
  `Recorded verdict: **${bm.recorded.verdict}** (${bm.recorded.source})`,
  '',
  bm.verdict,
  '',
  bm.correlationWarning,
  '');

writeFileSync(OUT, `${L.join('\n')}\n`);
console.log(`wrote ${OUT} (${L.length} lines)`);
